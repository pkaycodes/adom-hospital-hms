import { useEffect, useRef } from 'react';
import { useLocation, useNavigate } from 'react-router-dom';
import { Printer, X } from 'lucide-react';
import { useApi } from '../api';
import { ErrorNote, Loading } from '../components/ui';
import { dateOnly, dateTime, money, paymentMethod } from '../format';

function HospitalHead({
  settings,
  documentTitle,
  number,
  subline,
}: {
  settings: any;
  documentTitle: string;
  number: string;
  subline?: string;
}) {
  return (
    <div className="print-head">
      <div className="print-hospital">
        <div className="print-logo">
          {settings?.logo_url ? <img src={settings.logo_url} alt="" /> : (settings?.logo_text || 'H').slice(0, 3)}
        </div>
        <div>
          <h1>{settings?.name || 'Hospital'}</h1>
          {settings?.address && <p>{settings.address}</p>}
          <p>
            {[settings?.phone && `Tel: ${settings.phone}`, settings?.email].filter(Boolean).join(' · ')}
          </p>
        </div>
      </div>
      <div className="print-doc-title">
        <h2>{documentTitle}</h2>
        <div className="num mono">{number}</div>
        {subline && <div style={{ fontSize: 10, color: '#5d716d', marginTop: 2 }}>{subline}</div>}
      </div>
    </div>
  );
}

function Foot({ text }: { text?: string }) {
  return (
    <div className="print-foot">
      <div>{text || 'This document is computer generated by the hospital management system.'}</div>
      <div>Printed {dateTime(new Date().toISOString())} · Africa/Accra</div>
    </div>
  );
}

export default function PrintPage() {
  const location = useLocation();
  const navigate = useNavigate();
  const segments = location.pathname.split('/').filter(Boolean);
  const mode = segments[1] as 'invoice' | 'receipt' | 'consultation';
  const invoiceId = mode !== 'consultation' ? segments[2] : null;
  const paymentId = mode === 'receipt' ? segments[3] : null;
  const visitId = mode === 'consultation' ? segments[2] : null;

  const invoiceQuery = useApi<any>(invoiceId ? `/invoices/${invoiceId}` : null);
  const visitQuery = useApi<any>(visitId ? `/visits/${visitId}` : null);
  const settingsQuery = useApi<any>('/settings');
  const printed = useRef(false);

  const ready = !!(settingsQuery.data && (mode === 'consultation' ? visitQuery.data : invoiceQuery.data));

  useEffect(() => {
    if (!ready || printed.current) return;
    printed.current = true;
    const timer = setTimeout(() => window.print(), 600);
    return () => clearTimeout(timer);
  }, [ready]);

  const settings = settingsQuery.data?.settings;
  const error = settingsQuery.error || (mode === 'consultation' ? visitQuery.error : invoiceQuery.error);

  if (error) {
    return (
      <div className="print-shell">
        <div className="print-toolbar no-print">
          <button className="btn btn-secondary" onClick={() => navigate(-1)}>
            <X size={14} /> Close
          </button>
        </div>
        <ErrorNote message={error} />
      </div>
    );
  }

  if (!ready) {
    return (
      <div className="print-shell">
        <Loading label="Preparing document…" />
      </div>
    );
  }

  const invoice = invoiceQuery.data?.invoice;
  const payment = invoice?.payments?.find((p: any) => String(p.id) === String(paymentId));

  return (
    <div className="print-shell">
      <div className="print-toolbar no-print">
        <button className="btn btn-secondary" onClick={() => navigate(-1)}>
          <X size={14} /> Close
        </button>
        <button className="btn btn-primary" onClick={() => window.print()}>
          <Printer size={14} /> Print
        </button>
      </div>

      <div className="print-page">
        {mode === 'receipt' && invoice && payment && (
          <>
            <HospitalHead
              settings={settings}
              documentTitle="Payment receipt"
              number={payment.receipt_no}
              subline={payment.status === 'reversed' ? 'REVERSED' : 'Official receipt'}
            />
            <div className="print-meta">
              <div className="block">
                <div className="label">Received from</div>
                <div>
                  <strong>{invoice.patient_name}</strong>
                </div>
                <div>Patient ID: {invoice.patient_no}</div>
                {invoice.patient_phone && <div>Tel: {invoice.patient_phone}</div>}
              </div>
              <div className="block">
                <div className="label">Payment details</div>
                <div>Date: {dateTime(payment.paid_at)}</div>
                <div>Method: {paymentMethod(payment.method)}</div>
                {payment.momo_reference && <div>MoMo reference: {payment.momo_reference}</div>}
                <div>Recorded by: {payment.cashier_name || '—'}</div>
              </div>
              <div className="block">
                <div className="label">Invoice</div>
                <div>{invoice.invoice_no}</div>
                <div>Visit: {invoice.visit_no}</div>
                <div>Billed: {money(invoice.total)}</div>
              </div>
            </div>

            <div className="print-section-title">Services on this invoice</div>
            <table className="print-table">
              <thead>
                <tr>
                  <th>Description</th>
                  <th>Category</th>
                  <th style={{ textAlign: 'right' }}>Amount</th>
                </tr>
              </thead>
              <tbody>
                {invoice.items
                  .filter((i: any) => i.status === 'active')
                  .map((item: any) => (
                    <tr key={item.id}>
                      <td>
                        {item.description}
                        {item.quantity > 1 ? ` × ${item.quantity}` : ''}
                      </td>
                      <td>{item.category}</td>
                      <td style={{ textAlign: 'right' }}>{money(item.amount)}</td>
                    </tr>
                  ))}
              </tbody>
            </table>

            <div className="print-totals">
              <div className="line"><span>Invoice total</span><span>{money(invoice.total)}</span></div>
              <div className="line"><span>Total paid to date</span><span>{money(invoice.paid)}</span></div>
              <div className="line"><span>Outstanding balance</span><span>{money(invoice.balance)}</span></div>
              <div className="line grand"><span>Amount received now</span><span>{money(payment.amount)}</span></div>
            </div>

            <div className="print-text" style={{ marginTop: 18, border: 0, background: 'transparent', padding: 0 }}>
              {payment.method === 'momo'
                ? `Mobile Money payment confirmed against ${settings?.momo_number ? `the hospital number ${settings.momo_number}` : 'the hospital Mobile Money number'}.`
                : 'Cash received at the hospital cash desk.'}{' '}
              {invoice.balance > 0
                ? `A balance of ${money(invoice.balance)} remains outstanding.`
                : 'This invoice is fully settled.'}
            </div>

            <div className="signature">
              <div>Received by (cashier)</div>
              <div>Patient / guardian signature</div>
            </div>
            <Foot text={payment.status === 'reversed' ? 'This payment has been reversed by an administrator.' : undefined} />
          </>
        )}

        {mode === 'invoice' && invoice && (
          <>
            <HospitalHead
              settings={settings}
              documentTitle="Patient bill / invoice"
              number={invoice.invoice_no}
              subline={`Visit ${invoice.visit_no}`}
            />
            <div className="print-meta">
              <div className="block">
                <div className="label">Patient</div>
                <div><strong>{invoice.patient_name}</strong></div>
                <div>Patient ID: {invoice.patient_no}</div>
                {invoice.patient_phone && <div>Tel: {invoice.patient_phone}</div>}
              </div>
              <div className="block">
                <div className="label">Visit</div>
                <div>{invoice.visit_no}</div>
                <div>Date: {dateOnly(invoice.created_at)}</div>
                <div>Time: {dateTime(invoice.created_at).split(', ')[1] || ''}</div>
              </div>
              <div className="block">
                <div className="label">Payment methods</div>
                <div>Cash at cash desk</div>
                <div>Mobile Money {settings?.momo_number ? `to ${settings.momo_number}` : ''}</div>
              </div>
            </div>

            <div className="print-section-title">Charges</div>
            <table className="print-table">
              <thead>
                <tr>
                  <th>Description</th>
                  <th>Category</th>
                  <th style={{ textAlign: 'right' }}>Unit price</th>
                  <th style={{ textAlign: 'right' }}>Qty</th>
                  <th style={{ textAlign: 'right' }}>Amount</th>
                </tr>
              </thead>
              <tbody>
                {invoice.items
                  .filter((i: any) => i.status === 'active')
                  .map((item: any) => (
                    <tr key={item.id}>
                      <td>{item.description}</td>
                      <td>{item.category}</td>
                      <td style={{ textAlign: 'right' }}>{money(item.unit_price)}</td>
                      <td style={{ textAlign: 'right' }}>{item.quantity}</td>
                      <td style={{ textAlign: 'right' }}>{money(item.amount)}</td>
                    </tr>
                  ))}
                {!invoice.items.filter((i: any) => i.status === 'active').length && (
                  <tr>
                    <td colSpan={5} style={{ color: '#8a9c98' }}>No charges recorded.</td>
                  </tr>
                )}
              </tbody>
            </table>

            <div className="print-totals">
              <div className="line"><span>Total billed</span><span>{money(invoice.total)}</span></div>
              <div className="line"><span>Payments received</span><span>{money(invoice.paid)}</span></div>
              <div className="line grand"><span>Balance due</span><span>{money(invoice.balance)}</span></div>
            </div>

            <div className="print-section-title">Payments recorded</div>
            <table className="print-table">
              <thead>
                <tr>
                  <th>Receipt</th>
                  <th>Date</th>
                  <th>Method</th>
                  <th>Reference</th>
                  <th>Cashier</th>
                  <th style={{ textAlign: 'right' }}>Amount</th>
                </tr>
              </thead>
              <tbody>
                {invoice.payments.map((p: any) => (
                  <tr key={p.id}>
                    <td>{p.receipt_no}</td>
                    <td>{dateTime(p.paid_at)}</td>
                    <td>{paymentMethod(p.method)}</td>
                    <td>{p.momo_reference || '—'}</td>
                    <td>{p.cashier_name || '—'}</td>
                    <td style={{ textAlign: 'right' }}>
                      {money(p.amount)}
                      {p.status === 'reversed' ? ' (reversed)' : ''}
                    </td>
                  </tr>
                ))}
                {!invoice.payments.length && (
                  <tr>
                    <td colSpan={6} style={{ color: '#8a9c98' }}>No payments recorded yet.</td>
                  </tr>
                )}
              </tbody>
            </table>

            <div className="signature">
              <div>Prepared by</div>
              <div>Patient / guardian signature</div>
            </div>
            <Foot />
          </>
        )}

        {mode === 'consultation' && visitQuery.data && (
          <>
            <HospitalHead
              settings={settings}
              documentTitle="Consultation summary"
              number={visitQuery.data.visit.visit_no}
              subline={`Patient ID ${visitQuery.data.patient.patient_no}`}
            />
            <div className="print-meta">
              <div className="block">
                <div className="label">Patient</div>
                <div><strong>{visitQuery.data.patient.full_name}</strong></div>
                <div>
                  {visitQuery.data.patient.age} years ·{' '}
                  {visitQuery.data.patient.gender === 'male' ? 'Male' : 'Female'}
                </div>
                <div>{visitQuery.data.patient.phone || ''}</div>
                <div>NHIS: {visitQuery.data.patient.nhis_number || 'None'} ({visitQuery.data.patient.nhis_status})</div>
              </div>
              <div className="block">
                <div className="label">Visit</div>
                <div>{visitQuery.data.visit.visit_no}</div>
                <div>{dateTime(visitQuery.data.visit.created_at)}</div>
                <div>Reason: {visitQuery.data.visit.reason}</div>
              </div>
              <div className="block">
                <div className="label">Doctor</div>
                <div>{visitQuery.data.consultation?.doctor_name || '—'}</div>
                <div>
                  Consultation:{' '}
                  {visitQuery.data.consultation?.completed_at
                    ? dateTime(visitQuery.data.consultation.completed_at)
                    : 'In progress'}
                </div>
              </div>
            </div>

            {visitQuery.data.patient.allergies &&
              visitQuery.data.patient.allergies.toLowerCase() !== 'none known' && (
                <div className="print-text" style={{ color: '#b42318', borderColor: '#f6d5d1' }}>
                  <strong>Allergies:</strong> {visitQuery.data.patient.allergies}
                </div>
              )}

            {visitQuery.data.vitals && (
              <>
                <div className="print-section-title">Vital signs</div>
                <table className="print-table">
                  <tbody>
                    <tr>
                      <td><strong>Blood pressure</strong></td>
                      <td>
                        {visitQuery.data.vitals.bp_systolic
                          ? `${visitQuery.data.vitals.bp_systolic}/${visitQuery.data.vitals.bp_diastolic} mmHg`
                          : '—'}
                      </td>
                      <td><strong>Temperature</strong></td>
                      <td>{visitQuery.data.vitals.temperature ?? '—'} °C</td>
                      <td><strong>Pulse</strong></td>
                      <td>{visitQuery.data.vitals.pulse ?? '—'} bpm</td>
                    </tr>
                    <tr>
                      <td><strong>Respiratory rate</strong></td>
                      <td>{visitQuery.data.vitals.resp_rate ?? '—'} /min</td>
                      <td><strong>SpO₂</strong></td>
                      <td>{visitQuery.data.vitals.spo2 ?? '—'} %</td>
                      <td><strong>Glucose</strong></td>
                      <td>{visitQuery.data.vitals.glucose ?? '—'} mmol/L</td>
                    </tr>
                    <tr>
                      <td><strong>Weight</strong></td>
                      <td>{visitQuery.data.vitals.weight ?? '—'} kg</td>
                      <td><strong>Height</strong></td>
                      <td>{visitQuery.data.vitals.height ?? '—'} m</td>
                      <td><strong>Recorded</strong></td>
                      <td>{dateTime(visitQuery.data.vitals.recorded_at)}</td>
                    </tr>
                  </tbody>
                </table>
                <div className="print-section-title">Presenting complaints</div>
                <div className="print-text">{visitQuery.data.vitals.complaints}</div>
              </>
            )}

            {visitQuery.data.consultation ? (
              <>
                <div className="print-section-title">Diagnosis</div>
                <div className="print-text">
                  <strong>{visitQuery.data.consultation.diagnosis || 'Not recorded'}</strong>
                </div>
                <div className="print-section-title">Symptoms</div>
                <div className="print-text">{visitQuery.data.consultation.symptoms || '—'}</div>
                <div className="print-section-title">Clinical notes / examination</div>
                <div className="print-text">{visitQuery.data.consultation.clinical_notes || '—'}</div>
                {visitQuery.data.consultation.treatment_plan && (
                  <>
                    <div className="print-section-title">Treatment plan</div>
                    <div className="print-text">{visitQuery.data.consultation.treatment_plan}</div>
                  </>
                )}
                {visitQuery.data.consultation.follow_up_instructions && (
                  <>
                    <div className="print-section-title">Follow-up instructions</div>
                    <div className="print-text">{visitQuery.data.consultation.follow_up_instructions}</div>
                  </>
                )}
              </>
            ) : (
              <div className="print-text" style={{ marginTop: 14 }}>Consultation notes have not been recorded.</div>
            )}

            {visitQuery.data.labs.length > 0 && (
              <>
                <div className="print-section-title">Laboratory investigations</div>
                <table className="print-table">
                  <thead>
                    <tr>
                      <th>Test</th>
                      <th>Status</th>
                      <th>Result</th>
                    </tr>
                  </thead>
                  <tbody>
                    {visitQuery.data.labs.map((lab: any) => (
                      <tr key={lab.id}>
                        <td>{lab.test_name}</td>
                        <td>{lab.status.replace('_', ' ')}</td>
                        <td>{lab.result || 'Pending'}</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </>
            )}

            {visitQuery.data.prescriptions.length > 0 && (
              <>
                <div className="print-section-title">Prescriptions</div>
                <table className="print-table">
                  <thead>
                    <tr>
                      <th>Medication</th>
                      <th>Dosage</th>
                      <th>Frequency</th>
                      <th>Duration</th>
                      <th>Qty</th>
                      <th>Status</th>
                    </tr>
                  </thead>
                  <tbody>
                    {visitQuery.data.prescriptions.map((rx: any) => (
                      <tr key={rx.id}>
                        <td>{rx.drug_name}</td>
                        <td>{rx.dosage || '—'}</td>
                        <td>{rx.frequency || '—'}</td>
                        <td>{rx.duration || '—'}</td>
                        <td>{rx.quantity}</td>
                        <td>{rx.status}</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </>
            )}

            <div className="signature">
              <div>
                {visitQuery.data.consultation?.doctor_name || 'Doctor'}
                <br />
                Consulting doctor
              </div>
              <div>Date</div>
            </div>
            <Foot />
          </>
        )}

        {mode === 'receipt' && !payment && (
          <div className="empty">
            <h3>Receipt not found</h3>
            <p>This payment does not belong to the selected invoice.</p>
          </div>
        )}
      </div>
    </div>
  );
}
